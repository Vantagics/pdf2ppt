func rewriteWingdings(family, text string) (string, string, bool) {
	fam := strings.ToLower(family)
	dingbat := strings.Contains(fam, "wingdings") || strings.Contains(fam, "webdings")
	var b strings.Builder
	changed := false
	for _, r := range text {
		if dingbat && r >= 0xF020 && r <= 0xF0FF {
			if m, ok := wingdings[r-0xF000]; ok {
				b.WriteRune(m)
				changed = true
				continue
			}
		}
		// U+27A2 is the Wingdings chevron. Calibri has no glyph for it, so
		// PowerPoint draws an empty box. Segoe UI Symbol has the arrow.
		if r == 0x27A2 || r == 0x27A3 || r == 0x27A4 || (r >= 0x2190 && r <= 0x21FF && dingbat) {
			b.WriteRune(r)
			changed = true
			continue
		}
		b.WriteRune(r)
	}
	if !changed {
		return text, family, false
	}
	return b.String(), "Segoe UI Symbol", true
}

