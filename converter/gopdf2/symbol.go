func rewriteSymbol(family, text string) (string, string, bool) {
	fam := strings.ToLower(family)
	if !strings.Contains(fam, "symbol") {
		return text, family, false
	}
	var b strings.Builder
	changed := false
	for _, r := range text {
		if r >= 0xF000 && r <= 0xF0FF {
			if m, ok := symbolPUA[r-0xF000]; ok {
				b.WriteRune(m)
				changed = true
				continue
			}
		}
		b.WriteRune(r)
	}
	if !changed {
		return text, family, false
	}
	return b.String(), "Cambria Math", true
}
